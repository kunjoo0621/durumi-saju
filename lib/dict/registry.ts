const ENTRY_MAP: Record<string, DictEntry> = Object.fromEntries(
  ENTRY_LIST.map((e) => [`${e.category}/${e.slug}`, e]),
);

export function getDictEntry(
  category: DictCategory,
  slug: string,
): DictEntry | null {
  return ENTRY_MAP[`${category}/${slug}`] ?? null;
}

export function hasDictEntry(category: DictCategory, slug: string): boolean {
  return Boolean(ENTRY_MAP[`${category}/${slug}`]);
}

export function getAllDictEntries(): DictEntry[] {
  return ENTRY_LIST;
}

export function getDictEntriesByCategory(
  category: DictCategory,
): DictEntry[] {
  return ENTRY_LIST.filter((e) => e.category === category);
}
