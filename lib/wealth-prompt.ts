const PILLAR_LABEL: Record<WealthStarHit["pillar"], string> = {
  year: "년주",
  month: "월주",
  day: "일주",
  hour: "시주",
};

function formatJaeseong(facts: WealthFacts): string {
  if (facts.jaeseongAbsent) return "없음(무재)";
  return facts.jaeseong
    .map((s) => `${s.star}(${PILLAR_LABEL[s.pillar]}·${s.source})`)
    .join(", ");
}

function formatTimingWindows(windows: WealthTimingWindow[]): string {
  if (windows.length === 0) return "없음";
  return windows
    .map(
      (w) =>
        `${w.year}년(만 ${w.age}세, ${w.triggers.join("+")}${w.isPast ? "·이미 지난 시기" : "·앞으로의 시기"})`,
    )
    .join(", ");
}

function formatDaeunWealthYears(facts: WealthFacts): string {
  if (facts.daeunWealthYears.length === 0) return "없음";
  return facts.daeunWealthYears
    .map((d) => `${d.startAge}~${d.endAge}세 구간(${d.star} 대운)`)
    .join(", ");
}

// interest(관심사 4분법)와 jaeseongType/jaeGrip 사이의 "원하는 방식 vs 타고난 구조" 간극을
// 서버에서 결정론으로 미리 계산해 사실 블록에 명시한다 — LLM이 이 판단 자체를 스스로 하다
// false negative(간극이 있는데 못 잡음)를 내지 않도록, 감지는 코드가 하고 "왜 간극인지 풀어
// 설명하는 것"만 LLM에 맡긴다(§10 "관심사-구조 불일치 하드 규칙").
function detectInterestStructureGap(facts: WealthFacts): string {
  const { interest, jaeseongType, jaeGrip } = facts;
  const gaps: string[] = [];

  if (interest === "목돈·노후 준비" && jaeseongType === "편재우세") {
    gaps.push(
      "관심사=목돈·노후 준비(정재·안정 축적형 방식) vs 원국 구조=편재우세(승부·유동형 재성) — 원하는 방식과 타고난 구조가 다르다",
    );
  }
  if (interest === "지출·빚 관리" && jaeGrip === "신왕재왕") {
    gaps.push(
      "관심사=지출·빚 관리(방어 위주) vs 원국 구조=신왕재왕(그릇이 큰 편) — 실제로는 버는 힘·감당력이 넉넉한 구조인데 방어적인 질문을 하고 있다",
    );
  }
  if (interest === "투자로 불리기" && jaeGrip === "재다신약") {
    gaps.push(
      "관심사=투자로 불리기(적극 확장) vs 원국 구조=재다신약(그릇보다 재가 많아 관리가 먼저인 구조) — 불리기 전에 담는 그릇부터 다져야 하는 구조",
    );
  }
  if (interest === "사업·수입 키우기" && jaeseongType === "정재우세" && !facts.sikssangSaengjae) {
    gaps.push(
      "관심사=사업·수입 키우기(확장) vs 원국 구조=정재우세·식상생재 약함(안정·월급형에 가까운 구조) — 확장 의지와 원국이 잘 맞는 방식이 다를 수 있다",
    );
  }

  if (gaps.length === 0) {
    return "없음(관심사와 원국 구조가 크게 어긋나지 않음 — 이 경우 억지로 간극을 만들어내지 마라)";
  }
  return gaps.join(" / ");
}

function buildFactBlock(facts: WealthFacts, grade: WealthGrade, employmentStatus?: string): string {
  const lines = [
    `지금 재물 관심사(사용자가 직접 선택): ${facts.interest}`,
    `직업 상태(참고 — 예시·조언을 이 상태에 맞춰라): ${employmentStatus?.trim() || "미제공"}`,
    `일간: ${facts.dayStem}`,
    `재성(정재·편재) 탐지: ${formatJaeseong(facts)}`,
    `재성 유형: ${facts.jaeseongType}`,
    `재성 강도(가중 점수 — 절대값 자체는 언급 말고 강약 판단 근거로만 활용): ${facts.jaeseongStrength}`,
    `비겁(비견·겁재) 강도(가중 점수): ${facts.bigeopStrength}`,
    `신강/신약 수준: ${facts.strengthLevel}`,
    `재를 담는 그릇(신강신약×재성 2차원 4상한): ${facts.jaeGrip}`,
    `재다신약 여부: ${facts.jaedaShinyak ? "예" : "아니오"}`,
    `식상생재(벌이 파이프라인) 여부: ${facts.sikssangSaengjae ? "예" : "아니오"}`,
    `군겁쟁재(비겁이 적은 재를 두고 다투는 구조) 여부: ${facts.gunggeobJaengjae ? "예" : "아니오"}`,
    `재고(財庫, 재 오행의 창고 지지) 유무: ${facts.jaego ? "있음(보조 신호로만 — 아래 규칙 참조)" : "없음"}`,
    `용신이 재/식상을 반기는지: ${facts.yongshinFavorsWealth ? "예" : "아니오"}`,
    `타이밍 창(세운이 재성·식상·비겁을 건드리는 해): ${formatTimingWindows(facts.timingWindows)}`,
    `대운 중 재성이 들어오는 구간: ${formatDaeunWealthYears(facts)}`,
    `관심사-구조 불일치 감지(서버 계산값 — 있으면 반드시 짚어라): ${detectInterestStructureGap(facts)}`,
    `재물운 등급(서버 확정값 — 절대 변경 금지): ${grade}`,
  ];
  return lines.join("\n");
}

