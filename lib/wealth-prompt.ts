export function buildWealthPrompt(
  facts: WealthFacts,
  grade: WealthGrade,
  sajuText: string,
  employmentStatus?: string,
): string {
  const factBlock = buildFactBlock(facts, grade, employmentStatus);

  return [
    SYSTEM_RULES,
    "===== 사주 원국(참고용 — 이 텍스트에서 새 재물운 판정을 계산하지 마라, 문맥 보강만) =====",
    sajuText,
    "===== 재물 사실(엔진 확정값 — 이 사실 안에서만 해석) =====",
    factBlock,
    OUTPUT_SCHEMA,
  ].join("\n\n");
}
