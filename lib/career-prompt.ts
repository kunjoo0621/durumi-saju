export function buildCareerPrompt(
  facts: CareerFacts,
  grade: CareerGrade,
  sajuText: string,
  employmentStatus?: string,
  currentYear: number = new Date().getFullYear(),
): string {
  const factBlock = buildFactBlock(facts, grade, employmentStatus);
  const rules = SYSTEM_RULES
    .replace(/\{\{CURRENT_YEAR\}\}/g, String(currentYear))
    .replace(/\{\{PREV_YEAR\}\}/g, String(currentYear - 1));

  return [
    rules,
    "===== 사주 원국(참고용 — 이 텍스트에서 새 커리어 판정을 계산하지 마라, 문맥 보강만) =====",
    sajuText,
    "===== 커리어 사실(엔진 확정값 — 이 사실 안에서만 해석) =====",
    factBlock,
    OUTPUT_SCHEMA,
  ].join("\n\n");
}
