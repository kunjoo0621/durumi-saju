const PILLAR_LABEL: Record<CareerStarHit["pillar"], string> = {
  year: "년주",
  month: "월주",
  day: "일주",
  hour: "시주",
};

function formatGwanseong(facts: CareerFacts): string {
  if (facts.gwanseongAbsent) return "없음(무관)";
  return facts.gwanseong
    .map((s) => `${s.star}(${PILLAR_LABEL[s.pillar]}·${s.source})`)
    .join(", ");
}

function formatTimingWindows(windows: CareerTimingWindow[]): string {
  if (windows.length === 0) return "없음";
  return windows
    .map(
      (w) =>
        `${w.year}년(${w.age}세, ${w.triggers.join("+")}${w.isPast ? "·이미 지난 시기" : "·앞으로의 시기"})`,
    )
    .join(", ");
}

function formatDaeunCareerYears(facts: CareerFacts): string {
  if (facts.daeunCareerYears.length === 0) return "없음";
  return facts.daeunCareerYears
    .map((d) => `${d.startAge}~${d.endAge}세 구간(${d.star} 대운)`)
    .join(", ");
}

// 궁위(宮位) — 관성이 앉은 기둥을 인생 국면으로 번역(정통 궁위론: 년=초년·집안, 월=청년·사회,
// 일지=중년·내 자리, 시=말년). 판단은 여기서 끝났고 LLM은 "왜 그 국면의 자리 기운인지"를
// 풀어 쓰기만 한다(숫자·새 판정 생성 금지).
const PILLAR_DOMAIN: Record<CareerStarHit["pillar"], string> = {
  year: "초년·집안 뿌리 국면(집안·성장기가 준 직업관의 바탕)",
  month: "사회활동기 국면(직장·커리어의 주 무대, 20~40대 일터)",
  day: "중년·내 자리 국면(주도권을 쥐고 내 몫을 하는 시기)",
  hour: "말년·후반 커리어 국면(오래 가는 일·마무리 무대)",
};

export function formatGwanseongGungwi(facts: CareerFacts): string {
  if (facts.gwanseongAbsent)
    return "해당 없음(무관 — 궁위 대신 식상·인성·용신·대운 경로로 서술)";
  const seen = new Set<string>();
  const lines: string[] = [];
  for (const h of facts.gwanseong) {
    if (seen.has(h.pillar)) continue;
    seen.add(h.pillar);
    lines.push(`${PILLAR_LABEL[h.pillar]}(${PILLAR_DOMAIN[h.pillar]})에 ${h.star}`);
  }
  return lines.join(" / ");
}

// situation(상황 4분법)과 타고난 구조 사이의 "원하는 길 vs 타고난 구조" 간극을 서버에서
// 결정론으로 미리 계산해 사실 블록에 명시한다 — LLM이 이 판단을 스스로 하다 false negative를
// 내지 않도록, 감지는 코드가 하고 "왜 간극인지 풀어 설명하는 것"만 LLM에 맡긴다.
export function detectSituationStructureGap(facts: CareerFacts): string {
  const { situation, gwanseongType, careerGrip, sanggwanGyeongwan, gwanseongAbsent } = facts;
  const siksangWeak = facts.siksinStrength + facts.sanggwanStrength < 3;
  const gaps: string[] = [];

  if (situation === "진로 탐색" && gwanseongType === "관살혼잡") {
    gaps.push(
      "상황=진로 탐색 vs 구조=관살혼잡(안정과 승부, 두 갈래 기운이 같이 있음) — 방향이 왔다갔다하기 쉬운 구조라 '무엇이 맞나'보다 '기준 하나를 세우는 것'이 먼저인 결",
    );
  }
  if (situation === "현직 성장" && sanggwanGyeongwan) {
    gaps.push(
      "상황=현직 성장(지금 조직에서 잘 되고 싶음) vs 구조=규율과 마찰하는 기운(상관견관) — 조직 안에서 크고 싶은데 자기 방식이 틀보다 앞서는 결이라, 승진·평가에서 저항이 생기기 쉬운 지점을 관리 관점으로 다뤄야 함",
    );
  }
  if (situation === "현직 성장" && gwanseongAbsent) {
    gaps.push(
      "상황=현직 성장(조직에서의 성취) vs 구조=무관(조직 인연 자체가 헐거운 편) — 직함·승진 축보다 실력·전문성 축으로 크는 게 이 구조엔 더 자연스러운 결",
    );
  }
  if (situation === "이직 고민" && gwanseongType === "정관우세" && !sanggwanGyeongwan) {
    gaps.push(
      "상황=이직 고민(옮길까) vs 구조=정관우세(안정·누적형) — 한자리에서 신뢰가 쌓일수록 힘이 붙는 결이라, 옮김 자체보다 지금 자리에서 조건을 재협상하는 쪽이 결에 맞을 수 있음",
    );
  }
  if (situation === "독립·사업" && careerGrip === "관다신약") {
    gaps.push(
      "상황=독립·사업(내 길로 갈까) vs 구조=책임·자리를 감당할 그릇(일간 힘)이 아직 작은 편 — 판을 벌이기 전에 힘·기반부터 다지는 게 먼저인 결",
    );
  } else if (
    // 관다신약 케이스는 위에서 이미 커버 — 중복 방지(같은 뜻 문장 두 번 금지)
    situation === "독립·사업" &&
    (facts.siksangType === "무식상" || (gwanseongType === "정관우세" && siksangWeak))
  ) {
    gaps.push(
      "상황=독립·사업(자기 판을 짜고 싶음) vs 구조=조직·체계형(판을 새로 짜는 식상 기운은 약한 편) — 완전 독립보다 조직을 낀 확장(사내독립·파트너십·전문가 포지션)이 더 자연스러운 결",
    );
  }

  if (gaps.length === 0) {
    return "없음(상황과 구조가 크게 어긋나지 않음 — 이 경우 억지로 간극을 만들어내지 마라)";
  }
  return gaps.join(" / ");
}

// 구조가 "어느 길"에 가장 자연스럽게 기우는지 — 결정론 소프트 신호(단정 아님). 사용자가 여러
// 상황을 봐도 각각 "잘 맞아"로만 긍정하는 예스맨 문제를 막는다. 우선순위(계획 B7):
// 관다신약/신약관소(기반 다지기) > 관인상생(조직·전문가) > 독립(식상강∧관약 or 상관우세∧무관)
// > 정관우세(조직 누적) > 편관우세(돌파·승부).
function naturalFitLabel(facts: CareerFacts): string {
  let leanSituation: CareerSituation | null = null;
  let why = "";
  const siksangStrong = facts.siksinStrength + facts.sanggwanStrength >= 3;
  const gwanWeak = facts.gwanseongStrength < 3;

  if (facts.careerGrip === "관다신약" || facts.careerGrip === "신약관소") {
    leanSituation = "현직 성장";
    why = "책임·자리를 감당할 그릇(일간 힘)이 아직 작은 편이라, 급한 이직·독립보다 지금 자리에서 힘·기반부터 다지기";
  } else if (facts.gwaninSangsaeng) {
    leanSituation = "현직 성장";
    why = "관인상생(자격·인정이 자리를 밀어주는 순환)이 있어 조직·전문가 트랙에서 신뢰를 쌓아 크는 길";
  } else if ((facts.siksangType === "상관우세" && facts.gwanseongAbsent) || (siksangStrong && gwanWeak)) {
    leanSituation = "독립·사업";
    why = "재능·표현(식상)이 앞서고 조직 얽매임은 약한 편이라, 남 밑보다 자기 판을 짜는 독립·전문 길";
  } else if (facts.gwanseongType === "정관우세") {
    leanSituation = "현직 성장";
    why = "정관우세(안정·질서형)라 한 조직 안에서 꾸준히 누적하며 크는 결";
  } else if (facts.gwanseongType === "편관우세") {
    leanSituation = "이직 고민";
    why = "편관우세(돌파·승부형)라 안주보다 새 무대·도전에서 힘이 실리는 결";
  }

  if (!leanSituation) return "특정 길로 크게 기울지 않음 — 사용자 상황을 그대로 지지";
  if (leanSituation === facts.situation)
    return `사용자 상황(${facts.situation})과 구조 신호가 일치 — 잘 맞는다고 자연스럽게 확인`;
  return `구조 신호는 '${leanSituation}' 쪽이 조금 더 자연스러운 편(${why}) — 사용자는 '${facts.situation}'를 선택`;
}

// 그릇 4상한 raw 용어(신왕관쇠 등)를 factBlock에 넣으면 LLM이 본문에 베끼거나 비슷한 이름끼리
// 헷갈려 오기한다(신왕관쇠→신왕관소). 아예 뜻만 넘겨 LLM이 용어를 볼 일이 없게 한다.
export function careerGripPlain(grip: string): string {
  switch (grip) {
    case "신왕관왕":
      return "내 힘도 강하고 책임·자리를 감당하는 그릇도 큰 편(둘 다 넉넉)";
    case "신왕관쇠":
      return "내 힘은 강한데 조직·직위 기운은 아직 옅은 편(자유도가 높은 결)";
    case "관다신약":
      return "맡는 책임·자리는 큰데 그걸 감당할 그릇(내 힘)이 상대적으로 작은 편";
    case "신약관소":
      return "조직·직위 기운도 내 힘도 둘 다 은은한 편";
    default:
      return grip;
  }
}

// 식상 유형을 뜻으로 — 식신=한 우물 전문가형, 상관=규율 벗어난 창의·독립형.
function siksangPlain(type: string): string {
  switch (type) {
    case "식신우세":
      return "한 분야를 깊게 파는 전문가형 재능";
    case "상관우세":
      return "틀을 벗어나 자기 방식으로 만드는 창의·독립형 재능";
    case "식상혼재":
      return "깊게 파는 힘과 새로 짜는 힘이 섞인 재능";
    default:
      return "재능(식상) 신호는 옅은 편";
  }
}

function buildFactBlock(facts: CareerFacts, grade: CareerGrade, employmentStatus?: string): string {
  const lines = [
    `지금 상황(사용자가 직접 선택): ${facts.situation}`,
    `직업 상태(참고 — 예시·조언을 이 상태에 맞춰라. situation이 1순위, 이 값은 예시 톤 보조): ${employmentStatus?.trim() || "미제공"}`,
    `일간: ${facts.dayStem}`,
    `관성(정관·편관) 탐지: ${formatGwanseong(facts)}`,
    `관성 유형: ${facts.gwanseongType}`,
    `관성 궁위 해석(위치→인생 국면, 서버 결정값 — 이 국면 번역을 gwanseongDiagnosis에 반드시 반영): ${formatGwanseongGungwi(facts)}`,
    `관성 강도(가중 점수 — 절대값 자체는 언급 말고 강약 판단 근거로만): ${facts.gwanseongStrength}`,
    `식상(재능·표현) 유형: ${facts.siksangType} — 뜻: ${siksangPlain(facts.siksangType)}`,
    `인성(자격·인정·배움) 강도(가중 점수): ${facts.inseongStrength}${facts.inseongAbsent ? " — 인성 부재(독학·실전형)" : ""}`,
    `신강/신약 수준: ${facts.strengthLevel}`,
    `책임·자리를 담는 그릇(뜻으로만 서술 — 용어 이름 쓰지 말 것): ${careerGripPlain(facts.careerGrip)}`,
    `관다신약(책임은 큰데 그릇이 작은 구조) 여부: ${facts.gwandaSinyak ? "예 — 아래 절대 규칙 3 반드시 반영" : "아니오"}`,
    `관인상생(자격·인정이 자리를 밀어주는 순환) 여부: ${facts.gwaninSangsaeng ? "예" : "아니오"}`,
    `상관견관(자기 방식이 조직 규율과 마찰하는 기운) 여부: ${facts.sanggwanGyeongwan ? "예 — 순수 긍정 금지, 아래 절대 규칙 8 반드시 반영" : "아니오"}`,
    `무관(관성 없음 — 조직 얽매임이 약한 자유형) 여부: ${facts.gwanseongAbsent ? "예" : "아니오"}`,
    `용신이 관성/인성을 반기는지: ${facts.yongshinFavorsCareer ? "예" : "아니오"}`,
    `타이밍 창(세운이 관성·인성·식상을 건드리는 해): ${formatTimingWindows(facts.timingWindows)}`,
    `대운 중 관성이 들어오는 구간: ${formatDaeunCareerYears(facts)}`,
    `상황-구조 불일치 감지(서버 계산값 — 있으면 반드시 짚어라): ${detectSituationStructureGap(facts)}`,
    `구조가 자연스럽게 지지하는 길(소프트 신호 — 아래 '상황 vs 구조 정직' 규칙대로 활용): ${naturalFitLabel(facts)}`,
    `커리어운 등급(서버 확정값 — 절대 변경 금지): ${grade}`,
  ];
  return lines.join("\n");
}

