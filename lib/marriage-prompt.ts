const PILLAR_LABEL: Record<SpouseStarHit["pillar"], string> = {
  year: "년주",
  month: "월주",
  day: "일주",
  hour: "시주",
};

function formatSpouseStars(facts: MarriageFacts): string {
  if (facts.spouseStarAbsent) return "없음(무관/무재)";
  return facts.spouseStars
    .map((s) => `${s.star}(${PILLAR_LABEL[s.pillar]}·${s.source})`)
    .join(", ");
}

function formatTimingWindows(windows: TimingWindow[]): string {
  if (windows.length === 0) return "없음";
  return windows
    .map((w) => `${w.year}년(${w.age}세, ${w.triggers.join("+")}${w.isPast ? "·이미 지난 시기" : "·앞으로의 시기"})`)
    .join(", ");
}

function formatDaeunSpouseYears(facts: MarriageFacts): string {
  if (facts.daeunSpouseYears.length === 0) return "없음";
  return facts.daeunSpouseYears
    .map((d) => `${d.startAge}~${d.endAge}세 구간(${d.star} 대운)`)
    .join(", ");
}

// ★ facts.dayBranchGongmang은 이 엔진에서 구조적으로 항상 false다(일지는 자기 자신의 공망이
// 될 수 없음 — lib/marriage-facts.ts 주석 참조). 값어치 없는 상수이므로 사실 블록에 아예
// 노출하지 않는다 — 노출하면 LLM이 "공망 아님"이라는 무의미한 문장을 굳이 만들어낼 수 있다.
function formatSpouseStarDamage(facts: MarriageFacts): string {
  if (!facts.spouseStarDamaged) return "없음";
  return facts.spouseStarDamageReason.join(", ");
}

function buildFactBlock(facts: MarriageFacts, grade: MarriageGrade): string {
  const lines = [
    `성별: ${facts.sex === "female" ? "여명 (배우자성 = 관성: 정관·편관)" : "남명 (배우자성 = 재성: 정재·편재)"}`,
    `관계 상태: ${facts.maritalStatus}`,
    `일간 / 일지(배우자궁): ${facts.dayStem} / ${facts.dayBranch}`,
    `배우자성 탐지: ${formatSpouseStars(facts)}`,
    // 필드명은 gwansalHonjap 하나지만 의미는 성별에 따라 다르다: 여명=관살혼잡(정관+편관),
    // 남명=정편재혼잡(정재+편재). 라벨을 성별에 맞춰 분기해 LLM이 남명에게 "관살혼잡"이라는
    // 틀린 용어를 쓰지 않게 한다. (필드명 자체 rename은 DB/teaser/API 파급이라 금지 — lib/marriage-facts.ts 주석 참조.)
    facts.sex === "female"
      ? `관살혼잡(정관+편관 동시 존재): ${facts.gwansalHonjap ? "예" : "아니오"}`
      : `정편재혼잡(정재+편재 동시 존재): ${facts.gwansalHonjap ? "예" : "아니오"}`,
    `일지 지장간 구조(배우자 성격의 겹 — 본기=겉으로 드러나는 기본 결, 속결=같이 살아야 보이는 숨은 결): ${
      facts.spousePalaceHidden.length > 0
        ? facts.spousePalaceHidden.map((h) => `${h.position} ${h.star}`).join(" / ")
        : "없음"
    }`,
    `일지 합(배우자궁이 묶이는 관계): [${facts.dayBranchHap.join(", ") || "없음"}]`,
    `일지 충(배우자궁이 흔들리는 관계): [${facts.dayBranchChung.join(", ") || "없음"}]`,
    `배우자성 손상(배우자성이 다른 별에 극당하거나 충으로 깨지는 신호 — 존재/궁 안정도와 별개 축): ${facts.spouseStarDamaged ? `있음 (${formatSpouseStarDamage(facts)}) — 아래 절대 규칙 3-7 반드시 반영` : "없음"}`,
    `인연 신살: 도화 ${facts.dohwa ? "있음" : "없음"} / 홍염 ${facts.hongyeom ? "있음" : "없음"}`,
    `타이밍 창(세운이 일지·배우자성·도화홍염을 건드리는 해): ${formatTimingWindows(facts.timingWindows)}`,
    `대운 중 배우자성이 들어오는 구간: ${formatDaeunSpouseYears(facts)}`,
    `결혼운 등급(서버 확정값 — 절대 변경 금지): ${grade}`,
  ];
  return lines.join("\n");
}

