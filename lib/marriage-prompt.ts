  "teaserSummary": "무료 미리보기 1~2문장(30~60자). 등급이 좋다/아쉽다는 결만 살짝 암시하고, 구체적 진단·시기·조언은 절대 포함하지 않는다(스포일러 금지 — 전체 리포트를 열어야 자세히 보이게).",
