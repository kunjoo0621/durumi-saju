export function buildMarriagePrompt(facts: MarriageFacts, grade: MarriageGrade, sajuText: string): string {
  const factBlock = buildFactBlock(facts, grade);

  return [
    SYSTEM_RULES,
    "===== 사주 원국(참고용 — 이 텍스트에서 새 결혼운 판정을 계산하지 마라, 문맥 보강만) =====",
    sajuText,
    "===== 결혼 사실(엔진 확정값 — 이 사실 안에서만 해석) =====",
    factBlock,
    OUTPUT_SCHEMA,
  ].join("\n\n");
}
